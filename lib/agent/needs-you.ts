// NEEDS YOU (Yousif 2026-10-17): "Most of these Needs you should be done by you.
// Use common sense ... Upset customers should be sent to me but invoices and
// stuff should be done by you quickly." Every open row the hourly owner message
// could carry takes one of three roads:
//   owner  an upset buyer, money back, a legal threat; and a revision nobody
//          holds (only an owner moves a revision)
//   close  nothing is left to do: a thank-you, "it arrived"
//   agent  everything else: the agent takes it (POST /api/alpha/needs-you),
//          works it and closes it. The owner hears about it only when the agent
//          never picked it up, stopped, or could not finish it (agentFallback).
// Pure: no database here (the passes are in ./needs-you-desk.ts).

const HOUR = 3_600_000;

export type OwnerKind = "upset" | "refund" | "legal";
export type OwnerTag = OwnerKind | "revision";
export const OWNER_TAGS: OwnerTag[] = ["upset", "refund", "legal", "revision"];

/** The owner's words for each tag, first in the line. */
export const OWNER_TAG_WORDS: Record<OwnerTag, string> = {
  upset: "Upset buyer",
  refund: "Money back",
  legal: "Legal",
  revision: "Revision",
};

export function isOwnerTag(t: unknown): t is OwnerTag {
  return typeof t === "string" && (OWNER_TAGS as string[]).includes(t);
}

// Phrases that only look like damage ("the link is broken").
const NOT_DAMAGE =
  /\b(?:broken\s+(?:links?|urls?|downloads?|files?|images?|pages?)|(?:links?|urls?|downloads?|files?|images?|pages?)\s+(?:is\s+|are\s+|was\s+|were\s+|seems?\s+|looks?\s+)?broken)\b/gi;
// Phrases that only look like anger ("in the worst case").
const NOT_UPSET = /\b(?:worst[- ]case|not (?:upset|disappointed|complaining|angry)|no complaints?)\b/gi;

const LEGAL =
  /\b(?:lawyers?|attorneys?|solicitors?|lawsuit|legal action|small claims|(?:take|taking) (?:you|this|it|the shop) to court|consumer (?:affairs|protection)|trading standards|fair trading|accc|better business bureau|ombudsman|(?:i(?:'ll| will)|going to|gonna|will)\s+sue|su(?:e|ing) (?:you|your|the shop|this shop)|(?:open(?:ed|ing)?|fil(?:e|ed|ing)|start(?:ed|ing)?) (?:a |an )?(?:case|claim)|etsy (?:case|claim)|report(?:ed|ing)? (?:you|your shop|this shop|the shop)\b)/i;

const REFUND =
  /\b(?:refund(?:ed|s|ing)?|money back|reimburs\w*|charge ?backs?|(?:open(?:ed)?|fil(?:e|ed)) a dispute|dispute (?:the|this|it)|compensat\w*|cancel(?:l?ed|l?ing|lation)?\s+(?:my |the |this |our )?(?:order|purchase)|want to cancel|damaged|cracked|smashed|shattered|dented|scratched|crushed|creased|ripped|broken|(?:lost|missing) (?:in (?:the )?(?:post|mail|transit)|parcel|package)|(?:parcel|package) (?:was |is |has been )?(?:lost|stolen)|never (?:arrived|came|got here)|wrong (?:item|size|print|frame|canvas|poster|product)|reprint\w*\b.{0,40}\b(?:our cost|for free|free of charge|no charge)|at (?:your|our) (?:own )?cost|pay (?:me )?back)\b/i;

const UPSET =
  /\b(?:worst|terrible|awful|horrible|horrendous|dreadful|disgust\w*|furious|angry|livid|upset|disappointed|disappointing|unacceptable|ridiculous|appalling|outrage\w*|scam\w*|fraud\w*|rip-?\s?off|ripped (?:me )?off|never (?:again|order(?:ing)? (?:from you )?again|buy(?:ing)? (?:from you )?again)|not (?:happy|satisfied|pleased|impressed)|unhappy|dissatisfied|(?:1|one)[- ]star|bad review|negative review|complain(?:t|ts|ing)?|fed up|sick of|waste of (?:money|time)|unprofessional|liars?|pathetic)\b/i;

// "Is this AI?" in any form is the owner's: never answered, not even to deny it.
const AI_ASKED =
  /\b(?:ai[- ]?(?:generated|made|art|image|images|portrait|drawn|drawing)|made (?:by|with|using|in) (?:an? )?ai|(?:is|was|did|do) (?:this|it|that|you|they) (?:made (?:by|with|using) |use |used |done (?:by|with) )?(?:an? )?ai\b|(?:use|used|using|uses) ai\b|by ai\b|artificial intelligence|chat ?gpt|midjourney|dall-?e|stable diffusion|computer[- ]generated|generated by)\b/i;

// "AI" written as a word in capitals ("drawn by hand or by AI?"); lower case "ai" is only caught in the phrases above.
const AI_WORD = /(?<![\p{L}\p{N}])A\.?I\.?(?![\p{L}\p{N}])/u;

/**
 * The owner kinds in a buyer's words (or the row's own summary). Empty = not the
 * owner's. aiAsk:false for our own text, which says "AI portrait" as a matter of course.
 */
export function ownerKindsOf(text: string | null | undefined, opts: { aiAsk?: boolean } = {}): OwnerKind[] {
  if (!text) return [];
  const t = text.replace(NOT_DAMAGE, " ").replace(NOT_UPSET, " ");
  const kinds: OwnerKind[] = [];
  if (UPSET.test(t) || (opts.aiAsk !== false && (AI_ASKED.test(t) || AI_WORD.test(t)))) kinds.push("upset");
  if (REFUND.test(t)) kinds.push("refund");
  if (LEGAL.test(t)) kinds.push("legal");
  return kinds;
}

/** Cut quoted history and mail-app footers off a buyer's words. */
export function ownWords(text: string | null | undefined): string {
  if (!text) return "";
  return text
    .replace(/\bOn [^\n]{0,120}wrote:[\s\S]*$/, "")
    .replace(/-{2,}\s*Original Message\s*-{2,}[\s\S]*$/i, "")
    .replace(/\bFrom:\s[\s\S]{0,200}\bSent:\s[\s\S]*$/, "")
    .replace(/\b(?:Sent from (?:my |Yahoo|Outlook|Mail for)|Get Outlook for|Yahoo Mail:)[\s\S]*$/i, "")
    .trim();
}

// What a thank-you or an "it arrived" is made of.
const BENIGN: RegExp[] = [
  /\b(?:thank(?:s| you)(?: (?:so|very) much| heaps| a lot| again| for (?:everything|your (?:help|patience|hard work|time)|this|that|it|all))?|thx|ty|cheers|much appreciated|appreciate (?:it|this|you|that)|grateful)\b/gi,
  /\bgood news(?: indeed)?\b/gi,
  /\b(?:(?:this|that|it|they)(?:'s| is| was| are| look| looks)?\s+)?(?:so |really |absolutely |just |very )?(?:awesome|amazing|great|perfect|lovely|wonderful|beautiful|brilliant|fantastic|gorgeous|stunning|incredible|adorable|cute|good|nice)\b/gi,
  /\b(?:i |we )?(?:love|loved|adore|adored) (?:it|them|this|that)\b/gi,
  /\b(?:got (?:it|them)|received(?: it| them)?|(?:it|they|the (?:print|portrait|parcel|package|order|frame|canvas|poster|picture|file|painting)s?)\s+(?:has |have |just )*(?:arrived|came|been (?:received|delivered)))\b/gi,
  /\bhave a (?:great|good|nice|lovely|wonderful) (?:day|weekend|week|evening|night)\b/gi,
  /\b(?:kind |warm |best )?regards\b/gi,
];
const FILLER = new Set(
  "hi hello hey dear oh wow yay aw aww omg but and so much very really just all the a it is this that you me i we us our my your for again too also indeed already xo xx xxx best love today yesterday finally safely safe sound well here now".split(" "),
);
// An answer to something we asked ("Yes, thank you" to "shall I print it at 8x10?") is never nothing.
const ANSWER = /\b(?:yes|yeah|yep|yup|ok|okay|sure|no|nope|please|go ahead|do it|approved?|confirm(?:ed)?)\b/i;

/** Nothing to answer: thanks, praise, "it arrived". At most a signed name may be left over. */
export function thanksOnly(text: string | null | undefined): boolean {
  const own = ownWords(text);
  if (!own || own.length > 240 || own.includes("?") || ANSWER.test(own)) return false;
  let rest = own;
  for (const re of BENIGN) rest = rest.replace(re, " ");
  if (rest === own) return false; // not one thank-you or arrival phrase
  const words = (rest.match(/\p{L}+(?:'\p{L}+)?/gu) ?? []).filter((w) => !FILLER.has(w.toLowerCase()));
  return words.length <= 2 && words.every((w) => /^\p{Lu}/u.test(w));
}

/** An email reaction ("Jane reacted via Gmail"): nothing to answer. */
export function reactionOnly(text: string | null | undefined): boolean {
  return !!text && text.length < 200 && /\breacted (?:via gmail|to your (?:message|email))\b/i.test(text);
}

export type NeedsYouRow = {
  kind: string;
  summary: string;
  recommendation?: string | null;
  /** The buyer's own words (history and footers may still be on). */
  said?: string | null;
  /** stuck_order: why it is stuck (./limbo.ts StuckReason). */
  reason?: string | null;
  orderStatus?: string | null;
  revisions?: number | null;
  /** Set when the agent handed the row to an owner (POST /api/alpha/needs-you op owner). */
  ownerAsk?: { kinds?: unknown; note?: unknown } | null;
};

export type Road = { road: "owner" | "close" | "agent"; tags: OwnerTag[]; why: string };

/** Kinds that carry a buyer's email; only these can be closed as nothing to answer. */
const CLOSABLE_MAIL = ["reply_unclear", "buyer_question"];

export function roadOf(r: NeedsYouRow): Road {
  if (r.ownerAsk) {
    const kinds = Array.isArray(r.ownerAsk.kinds) ? r.ownerAsk.kinds.filter(isOwnerTag) : [];
    return { road: "owner", tags: kinds, why: "handed to an owner" };
  }
  // Our own summary and advice can name damage or money back (a legacy card copies the buyer's
  // complaint into its summary); only the buyer's words can ask whether it is AI.
  const ours = ownerKindsOf([r.summary, r.recommendation].filter(Boolean).join("\n"), { aiAsk: false });
  const theirs = ownerKindsOf(ownWords(r.said));
  const kinds = (["upset", "refund", "legal"] as OwnerKind[]).filter((k) => ours.includes(k) || theirs.includes(k));
  if (kinds.length) return { road: "owner", tags: kinds, why: kinds.join(", ") };
  if (r.kind === "stuck_order" && r.reason === "no_designer" && (r.revisions ?? 0) > 0) {
    return { road: "owner", tags: ["revision"], why: "a revision nobody holds; only an owner moves a revision" };
  }
  if (CLOSABLE_MAIL.includes(r.kind)) {
    if (reactionOnly(r.said)) return { road: "close", tags: [], why: "an emoji reaction, nothing to answer" };
    // An approval waits on a judgment ("Good news, thank you!" may be a yes), so the agent reads it.
    if (r.orderStatus !== "awaiting_approval" && thanksOnly(r.said)) return { road: "close", tags: [], why: "a thank-you, nothing to answer" };
  }
  return { road: "agent", tags: [], why: "mine to work" };
}

/** Untaken this long past its grace = the agent side is not running: the owner hears. */
export const AGENT_PICKUP_HOURS = 3;
/** A taken row that is still open is taken again after this. */
export const AGENT_RETAKE_HOURS = 2;
/** After this many goes the owner hears, with the agent's last note. */
export const AGENT_MAX_TAKES = 3;
/** Past the most goes the row is still the agent's: one more go a day, never quiet for good (2026-10-23). */
export const AGENT_DAILY_RETAKE_HOURS = 24;
/** Taken but not taken again for this long = the agent side stopped: the owner hears. */
export const AGENT_STALLED_HOURS = 6;
/** Rows one take hands over (one agent run works them). */
export const AGENT_TAKE_LIMIT = 12;

export type AgentState = { takes: number; takenAt: string | null; note: string | null };

export function agentStateOf(detail: Record<string, unknown>): AgentState {
  return {
    takes: typeof detail.agentTakes === "number" ? detail.agentTakes : 0,
    takenAt: typeof detail.agentTakenAt === "string" ? detail.agentTakenAt : null,
    note: typeof detail.agentNote === "string" ? detail.agentNote : null,
  };
}

function hoursSince(iso: string | null, now: Date): number {
  const at = iso ? Date.parse(iso) : NaN;
  return Number.isNaN(at) ? Infinity : (now.getTime() - at) / HOUR;
}

/**
 * Why an agent row reaches the owner after all, or null while it is the
 * agent's: never picked up (the agent side is not running), stalled (taken,
 * then not again for AGENT_STALLED_HOURS), or tried AGENT_MAX_TAKES times.
 */
export function agentFallback(createdAt: Date, graceHours: number, a: AgentState, now: Date): "never picked up" | "stalled" | "tried" | null {
  if (!a.takes) return (now.getTime() - createdAt.getTime()) / HOUR >= graceHours + AGENT_PICKUP_HOURS ? "never picked up" : null;
  const since = hoursSince(a.takenAt, now);
  if (since >= AGENT_STALLED_HOURS) return "stalled";
  if (a.takes >= AGENT_MAX_TAKES && since >= AGENT_RETAKE_HOURS) return "tried";
  return null;
}

/**
 * The agent may take it now: past its grace and not taken in the last
 * AGENT_RETAKE_HOURS; past the most goes, once a day (AGENT_DAILY_RETAKE_HOURS).
 */
export function takeable(createdAt: Date, graceHours: number, a: AgentState, now: Date): boolean {
  if ((now.getTime() - createdAt.getTime()) / HOUR < graceHours) return false;
  if (a.takes >= AGENT_MAX_TAKES) return hoursSince(a.takenAt, now) >= AGENT_DAILY_RETAKE_HOURS;
  return !a.takes || hoursSince(a.takenAt, now) >= AGENT_RETAKE_HOURS;
}
